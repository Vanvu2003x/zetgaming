import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { pool } from './db/pool.mjs';
import { env } from './config/env.mjs';
import { currentUser, requireAuth, requireRole } from './middleware/auth.mjs';
import { dbContext, validateJson } from './middleware/request.mjs';
import { errorHandler, notFound } from './middleware/errors.mjs';
import { csrfToken, requireCsrf } from './middleware/csrf.mjs';
import { requestLogging } from './middleware/logging.mjs';
import { healthRouter } from './modules/health/routes.mjs';
import { catalogRouter } from './modules/catalog/routes.mjs';
import { authRouter } from './modules/auth/routes.mjs';
import { ordersRouter } from './modules/orders/routes.mjs';
import { dispatchRouter } from './modules/dispatch/routes.mjs';
import { storefrontRouter } from './modules/storefront/routes.mjs';

export function createApp() {
  const app = express();
  app.disable('x-powered-by');
  app.set('trust proxy', 'loopback');
  app.use(helmet({ contentSecurityPolicy: true, hsts: env.nodeEnv === 'production' }));
  app.use(cors({ origin: (origin, callback) => !origin || env.allowedOrigins.includes(origin) ? callback(null, true) : callback(new Error('Origin không được phép')), credentials: true }));
  app.use(rateLimit({ windowMs: 60_000, limit: 120, standardHeaders: 'draft-7', legacyHeaders: false }));
  app.use(requestLogging);
  app.use(express.json({ limit: '256kb' }));
  app.use(express.urlencoded({ extended: false, limit: '64kb' }));
  app.use(cookieParser());
  app.use(csrfToken);
  app.use(dbContext(pool));
  app.use(validateJson);
  app.use(currentUser);
  app.use('/api', healthRouter);
  app.get('/api/csrf', (req, res) => res.json({ csrf_token: req.csrfToken }));
  app.use('/api', catalogRouter);
  app.use('/api', storefrontRouter);
  app.use('/api/auth', requireCsrf, authRouter);
  app.use('/api', requireCsrf, requireAuth, ordersRouter);
  app.use('/api', dispatchRouter);
  app.use(notFound);
  app.use(errorHandler);
  return app;
}
