import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { pool } from './db/pool.mjs';
import { env } from './config/env.mjs';
import { currentUser } from './middleware/auth.mjs';
import { guestSession } from './middleware/guest.mjs';
import { dbContext, validateJson } from './middleware/request.mjs';
import { errorHandler, notFound } from './middleware/errors.mjs';
import { csrfToken, requireCsrf } from './middleware/csrf.mjs';
import { requestLogging } from './middleware/logging.mjs';
import { healthRouter } from './modules/health/routes.mjs';
import { catalogRouter } from './modules/catalog/routes.mjs';
import { packageCreateRouter } from './modules/catalog/package-create.mjs';
import { gameCreateRouter } from './modules/catalog/game-create.mjs';
import { categoriesRouter } from './modules/catalog/categories.mjs';
import { createUploadsRouter } from './modules/catalog/uploads.mjs';
import { authRouter } from './modules/auth/routes.mjs';
import { adminCustomersRouter } from './modules/auth/admin-customers.mjs';
import { adminSecurityRouter } from './modules/auth/admin-security.mjs';
import { adminReportsRouter } from './modules/reports/admin-reports.mjs';
import { adminPaymentRouter } from './modules/orders/admin-payment.mjs';
import { adminCouponsRouter } from './modules/orders/admin-coupons.mjs';
import { reconciliationRouter } from './modules/orders/reconciliation.mjs';
import { gmailReconciliationRouter } from './modules/orders/gmail-reconciliation.mjs';
import { contentRouter } from './modules/content/routes.mjs';
import { ordersRouter } from './modules/orders/routes.mjs';
import { adminFulfillmentRouter } from './modules/orders/admin-fulfillment.mjs';
import { adminLifecycleRouter } from './modules/orders/admin-lifecycle.mjs';
import { couponPreviewRouter } from './modules/orders/coupon-preview.mjs';
import { dispatchRouter } from './modules/dispatch/routes.mjs';
import { storefrontRouter } from './modules/storefront/routes.mjs';
import { savedInputsRouter } from './modules/storefront/saved-inputs.mjs';
import { walletRouter } from './modules/wallet/routes.mjs';
import { khoablackSyncRouter } from './modules/providers/khoablack-sync.mjs';

export function createApp() {
  const app = express();
  app.disable('x-powered-by');
  app.set('trust proxy', 'loopback');
  app.use(helmet({ contentSecurityPolicy: true, hsts: env.nodeEnv === 'production' }));
  app.use(cors({ origin: (origin, callback) => {
    if (!origin || env.allowedOrigins.includes(origin)) return callback(null, true);
    const error = new Error('Nguồn yêu cầu không hợp lệ');
    error.statusCode = 403;
    callback(error);
  }, credentials: true }));
  app.use(rateLimit({ windowMs: 60_000, limit: 120, standardHeaders: 'draft-7', legacyHeaders: false }));
  app.use(requestLogging);
  app.use(express.json({ limit: '256kb' }));
  app.use(express.urlencoded({ extended: false, limit: '64kb' }));
  app.use(cookieParser());
  app.use(guestSession);
  app.use(csrfToken);
  app.use(dbContext(pool));
  app.use(validateJson);
  app.use(currentUser);
  app.use('/api', healthRouter);
  app.get('/api/csrf', (req, res) => res.json({ csrf_token: req.csrfToken }));
  app.use('/api', catalogRouter);
  app.use('/api', adminCustomersRouter);
  app.use('/api', adminSecurityRouter);
  app.use('/api', adminReportsRouter);
  app.use('/api', adminPaymentRouter);
  app.use('/api', adminCouponsRouter);
  app.use('/api', contentRouter);
  app.use('/api', packageCreateRouter);
  app.use('/api', gameCreateRouter);
  app.use('/api', categoriesRouter);
  app.use('/api', createUploadsRouter());
  app.use('/api', storefrontRouter);
  app.use('/api', savedInputsRouter);
  app.use('/api', reconciliationRouter);
  app.use('/api', gmailReconciliationRouter);
  app.use('/api', walletRouter);
  app.use('/api', khoablackSyncRouter);
  app.use('/api', couponPreviewRouter);
  app.use('/api/auth', requireCsrf, authRouter);
  app.use('/api', requireCsrf, ordersRouter);
  app.use('/api', adminFulfillmentRouter);
  app.use('/api', adminLifecycleRouter);
  app.use('/api', dispatchRouter);
  app.use(notFound);
  app.use(errorHandler);
  return app;
}
