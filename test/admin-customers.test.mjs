import 'dotenv/config';
import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import express from 'express';
import cookieParser from 'cookie-parser';
import pg from 'pg';
import { adminCustomersRouter } from '../backend/modules/auth/admin-customers.mjs';
import { csrfToken } from '../backend/middleware/csrf.mjs';

test('admin customer controls protect the last admin and revoke sessions', async t => {
  const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL });
  const db = await pool.connect();
  t.after(async () => { await db.query('ROLLBACK'); db.release(); await pool.end(); });
  await db.query('BEGIN');
  await db.query("UPDATE users SET active=false WHERE role='admin'");
  const admin = randomUUID(), customer = randomUUID();
  await db.query("INSERT INTO users(id,email,password_hash,role,active) VALUES($1,$2,'unused','admin',true),($3,$4,'unused','customer',true)", [admin, admin + '@fixture.test', customer, customer + '@fixture.test']);
  await db.query("INSERT INTO sessions(token_hash,user_id,expires_at) VALUES('customer-session',$1,now()+interval '1 hour')", [customer]);
  const app = express();
  app.use(express.json(), cookieParser(), csrfToken, (req, _res, next) => { req.db = db; req.user = { id: admin, role: 'admin' }; next(); });
  app.get('/csrf', (req, res) => res.json({ token: req.csrfToken }));
  app.use('/api', adminCustomersRouter);
  app.use((error, _req, res, _next) => res.status(error.statusCode || 500).json({ error: error.message }));
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(() => { server.closeAllConnections(); server.close(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const seed = await fetch(base + '/csrf');
  const token = (await seed.json()).token;
  const cookie = seed.headers.getSetCookie()[0].split(';')[0];
  const headers = { cookie, 'x-csrf-token': token, 'content-type': 'application/json' };
  const list = await (await fetch(base + '/api/admin/customers', { headers })).json();
  assert.equal(list.find(row => row.id === customer).session_count, 1);
  const locked = await fetch(base + '/api/admin/customers/' + customer, { method: 'PATCH', headers, body: JSON.stringify({ active: false, tier: 'vip' }) });
  const lockedBody = await locked.json(); assert.equal(locked.status, 200, JSON.stringify(lockedBody));
  assert.equal((await db.query('SELECT active,tier FROM users WHERE id=$1', [customer])).rows[0].active, false);
  assert.equal((await db.query('SELECT COUNT(*) FROM sessions WHERE user_id=$1', [customer])).rows[0].count, '0');
  const last = await fetch(base + '/api/admin/customers/' + admin, { method: 'PATCH', headers, body: JSON.stringify({ active: false }) });
  const lastBody = await last.json(); assert.equal(last.status, 400, JSON.stringify(lastBody));
});
